"""Compile the V4.8 SVG paths and motion keyframes into small C++ tables.

The firmware never parses SVG or JSON. This generator uses only Python's stdlib.
"""
from __future__ import annotations

import json
import math
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "design" / "v48"
OUTPUT = ROOT / "src" / "app" / "Pages" / "Face" / "face_data.h"
TOKEN = re.compile(r"[A-Za-z]|[-+]?(?:\d*\.\d+|\d+\.?\d*)")
PARAMS = {"M": 2, "L": 2, "H": 1, "V": 1, "Q": 4, "C": 6, "A": 7, "Z": 0}


def points(path: str) -> list[tuple[int, int]]:
    tokens = TOKEN.findall(path)
    out: list[tuple[float, float]] = []
    i = 0
    cmd = ""
    x = y = sx = sy = 0.0
    while i < len(tokens):
        if tokens[i].isalpha():
            cmd = tokens[i]
            i += 1
        if cmd not in PARAMS:
            raise ValueError(f"Unsupported path command {cmd!r}: {path}")
        if cmd == "Z":
            if out and out[-1] != (sx, sy):
                out.append((sx, sy))
            cmd = ""
            continue
        n = PARAMS[cmd]
        values = list(map(float, tokens[i:i+n]))
        if len(values) != n:
            raise ValueError(path)
        i += n
        if cmd == "M":
            x, y = values; sx, sy = x, y; out.append((x, y)); cmd = "L"
        elif cmd == "L":
            x, y = values; out.append((x, y))
        elif cmd == "H":
            x = values[0]; out.append((x, y))
        elif cmd == "V":
            y = values[0]; out.append((x, y))
        elif cmd in ("Q", "C"):
            start = (x, y)
            for step in range(1, 9):
                t = step / 8
                if cmd == "Q":
                    cx, cy, ex, ey = values
                    px = (1-t)**2*x + 2*(1-t)*t*cx + t*t*ex
                    py = (1-t)**2*y + 2*(1-t)*t*cy + t*t*ey
                else:
                    c1x, c1y, c2x, c2y, ex, ey = values
                    px = (1-t)**3*x + 3*(1-t)**2*t*c1x + 3*(1-t)*t*t*c2x + t**3*ex
                    py = (1-t)**3*y + 3*(1-t)**2*t*c1y + 3*(1-t)*t*t*c2y + t**3*ey
                out.append((px, py))
            x, y = ex, ey
        else:
            rx, ry, rotation, large, sweep, ex, ey = values
            if rotation != 0 or y != ey or abs(abs(ex-x)-2*rx) > 0.1 or large != 1:
                raise ValueError(f"Arc must be a half ellipse: {path}")
            cx = (x + ex) / 2
            cy = y
            start = math.pi if x < ex else 0.0
            delta = -math.pi if sweep == 0 else math.pi
            for step in range(1, 17):
                t = start + delta * step / 16
                out.append((cx + rx*math.cos(t), cy + ry*math.sin(t)))
            x, y = ex, ey
    return [(round(px), round(py)) for px, py in out]


def main() -> None:
    catalogue = json.loads((SOURCE / "expression_catalogue.json").read_text())
    motion = json.loads((SOURCE / "motion_timeline.json").read_text())
    all_points = []
    shapes = []
    poses = []
    faces = []
    for entry in catalogue:
        shape_start = len(shapes)
        for shape in entry["shapes"]:
            pts = points(shape["d"])
            start = len(all_points)
            all_points.extend(pts)
            role = 1 if shape["role"] == "eyes" else 2 if shape["role"] == "mouth" else 0
            color = 1 if shape.get("c") in ("bright", "ice") else 0
            shapes.append((start, len(pts), min(round(shape.get("w", 0)), 255),
                           role, color, int(shape.get("fill", False))))
        timeline = motion[entry["id"]]
        pose_start = len(poses)
        for pose in timeline["poses"]:
            poses.append((round(pose["t"]*1000), round(pose.get("x", 0)*10),
                          round(pose.get("y", 0)*10), round(pose.get("r", 0)*10),
                          round(pose.get("ly", 1)*100), round(pose.get("ry", 1)*100),
                          round(pose.get("my", 1)*100)))
        faces.append((entry["id"], shape_start, len(entry["shapes"]), pose_start,
                      len(timeline["poses"]), timeline["cycleMs"]))
    lines = ["// Generated by tools/generate_face_data.py from design/v48/*.json.",
             "#pragma once", "#include <stdint.h>", "namespace FaceData {",
             "struct Point { int16_t x, y; };",
             "struct Shape { uint16_t start; uint8_t count, width, role, color, fill; };",
             "struct Pose { uint16_t t; int16_t x10, y10, r10; uint8_t ly, ry, my; };",
             "struct Face { const char *id; uint16_t shape_start; uint8_t shape_count; uint16_t pose_start; uint8_t pose_count; uint16_t cycle_ms; };",
             "static const Point points[] = {"]
    lines += [f"{{{x},{y}}}," for x, y in all_points]
    lines += ["};", "static const Shape shapes[] = {"]
    lines += ["{" + ",".join(map(str, item)) + "}," for item in shapes]
    lines += ["};", "static const Pose poses[] = {"]
    lines += ["{" + ",".join(map(str, item)) + "}," for item in poses]
    lines += ["};", "static const Face faces[] = {"]
    lines += [f'{{"{id}",{ss},{sc},{ps},{pc},{cy}}},' for id,ss,sc,ps,pc,cy in faces]
    lines += ["};", f"static constexpr uint8_t face_count = {len(faces)};", "}"]
    OUTPUT.write_text("\n".join(lines) + "\n")
    print(f"Generated {len(faces)} faces, {len(shapes)} shapes, {len(all_points)} path points")


if __name__ == "__main__":
    main()
